"""R3 report: VaR/ES backtesting (reports/market_var_backtest.md), built from results/market/backtest/ only."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, cast

import pandas as pd

SRC = Path("results/market/backtest")
REF = "fhs_garch_t"
LABEL = {
    "historical": "Historical simulation",
    "normal": "Normal (variance-covariance)",
    "student_t": "Student-t (unconditional)",
    "ewma": "EWMA / RiskMetrics λ=0.94",
    "garch_t": "GARCH(1,1)-t",
    "gjr_t": "GJR-GARCH(1,1)-t",
    "fhs_garch_t": "Filtered HS (GARCH-t)",
    "evt_garch_t": "Conditional EVT (GARCH-t + GPD)",
    "lgbm_quantile": "LightGBM quantile (ML)",
    "lgbm_vol_fhs": "LightGBM volatility + FHS (ML)",
}
ML = ("lgbm_quantile", "lgbm_vol_fhs")
GARCH = ("garch_t", "gjr_t", "fhs_garch_t", "evt_garch_t")


Rec = dict[Any, dict[str, Any]]


def _rec(df: pd.DataFrame) -> Rec:
    """Row records keyed by the index: plain dict access keeps mypy --strict happy with scalars."""
    return cast(Rec, df.to_dict("index"))


def _p(x: float) -> str:
    return "n/a" if pd.isna(x) else ("<0.001" if x < 0.001 else f"{x:.3f}")


def passed_years(py: pd.DataFrame, window: int, alpha: float) -> Rec:
    m = py[(py["window"] == window) & (py["level"] == 0.99)]
    m = m.assign(passed=(m["p_uc"] > alpha) & (m["p_cc"] > alpha))
    t = m.groupby("model").agg(
        years=("year", "nunique"),
        passed=("passed", "sum"),
        amber=("zone", lambda z: int((z == "amber").sum())),
        red=("zone", lambda z: int((z == "red").sum())),
    )
    return _rec(t.sort_values("passed", ascending=False))


def market_backtest() -> str | None:  # noqa: PLR0915 (linear report assembly)
    if not (SRC / "backtest.json").exists():
        return None
    meta: dict[str, Any] = json.loads((SRC / "backtest.json").read_text())
    s = pd.read_csv(SRC / "summary.csv")
    py = pd.read_csv(SRC / "per_year.csv")
    rg = pd.read_csv(SRC / "regimes.csv")
    cfg, d, comp = meta["config"], meta["data"], meta["comparisons"]
    w, alpha = cfg["backtest"]["window"], cfg["backtest"]["alpha"]
    main = _rec(s[(s["portfolio"] == "main") & (s["window"] == w)].set_index(["model", "level"]))
    models = [m for m in LABEL if (m, 0.99) in main]
    py_tab = passed_years(py, w, alpha)
    n = d["n_forecast_days"]

    wts = ", ".join(f"{k} {v:.0%}" for k, v in cfg["portfolio"]["weights"].items())
    lines = [
        "# Market risk: VaR/ES backtesting (Module B)",
        "",
        f"_Generated by `scripts/report.py` from `{SRC}/` (run {meta['run']['utc']}, arch {meta['run']['arch']}). "
        "Not investment advice: this measures risk, it makes no return forecasts._",
        "",
        "## Set-up",
        "",
        f"- **Portfolio** (EUR investor, ECB data only): {wts}, rebalanced daily. FX positions are foreign-currency "
        "cash valued at the ECB reference rate; bonds are constant-maturity AAA zero-coupon positions on the ECB "
        "euro-area yield curve (return = −T·Δy + carry). Equities are not included: Stooq's terms were never cleared, "
        "so the plan's FX/rates fallback is used.",
        f"- **Data:** daily returns {d['first_return']} to {d['last_return']} ({d['n_returns']:,} days). Portfolio daily "
        f"SD {d['portfolio_daily_sd_pct']:.3f}%; worst day {d['worst_day']} (loss {d['worst_day_loss_pct']:.2f}%).",
        f"- **Protocol:** one-day forecasts for every day from {d['first_forecast']} ({n:,} days), each from the previous "
        f"{w} days only (rolling window, re-estimated daily; ML models refitted every "
        f"{cfg['backtest']['ml_refit_every']} days). All windows (250/500/1000) start forecasting on the same day, so "
        "every model is scored on identical days. Regimes were fixed in `config/market.toml` before the run.",
        "- **Levels:** VaR 99% (Basel backtesting) and 97.5%; ES 97.5% (FRTB basis, BCBS MAR33.3).",
        f"- **Traffic light:** zones from the binomial CDF (green < 95%, red ≥ 99.99%); for 250 days at 99% this gives "
        f"amber from {meta['zone_counts_250_99']['amber_from']} and red from {meta['zone_counts_250_99']['red_from']} "
        "exceptions, matching the BCBS MAR32 table.",
        "",
        f"## 99% VaR, full sample ({w}-day window, {n:,} days, {n * 0.01:.0f} exceptions expected)",
        "",
        "| Model | Exceptions | Rate | Kupiec p | Independence p | Cond. coverage p | Days in green / amber / red (trailing 250d) | Max exceptions in 250d |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for m in models:
        r = main[(m, 0.99)]
        lines.append(
            f"| {LABEL[m]} | {int(r['exceptions'])} | {r['rate']:.2%} | {_p(r['p_uc'])} | {_p(r['p_ind'])} | "
            f"{_p(r['p_cc'])} | {r['share_green']:.0%} / {r['share_amber']:.0%} / {r['share_red']:.0%} | "
            f"{int(r['max_250d'])} |"
        )
    lines += [
        "",
        "![99% VaR vs losses](figures/market_var_path.png)",
        "",
        f"## 97.5% VaR and ES ({w}-day window)",
        "",
        "Z2 is the Acerbi–Szekely test 2 statistic: 0 if ES is right, negative if ES is too low; indicative zones "
        "> −0.70 green, > −1.8 amber. The residual test is a one-sided bootstrap on (L−ES)/ES on exception days "
        "(small p = ES too low). FZ0 is the joint VaR/ES scoring function (lower is better).",
        "",
        "| Model | Exceptions | Rate | Kupiec p | Cond. coverage p | Z2 (zone) | ES residual p | FZ0 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for m in models:
        r = main[(m, 0.975)]
        z2: str = "n/a (VaR only)" if pd.isna(r["z2"]) else f"{r['z2']:+.2f} ({r['z2_zone']})"
        fz: str = "n/a" if pd.isna(r["fz0"]) else f"{r['fz0']:.4f}"
        lines.append(
            f"| {LABEL[m]} | {int(r['exceptions'])} | {r['rate']:.2%} | {_p(r['p_uc'])} | {_p(r['p_cc'])} | {z2} | "
            f"{_p(r['p_es_residual'])} | {fz} |"
        )

    lines += [
        "",
        f"## Calm and stressed periods: calendar years (99% VaR, {w}-day window)",
        "",
        f"A year passes when both Kupiec and Christoffersen conditional coverage have p > {alpha}. Zones use the "
        "binomial CDF for that year's number of days.",
        "",
        "| Model | Years passed | Amber years | Red years |",
        "|---|---|---|---|",
    ]
    for m, r in py_tab.items():
        lines.append(f"| {LABEL[m]} | {r['passed']} of {r['years']} | {r['amber']} | {r['red']} |")
    lines += ["", "![Years passed](figures/market_passed_years.png)", ""]

    rr = rg[(rg["window"] == w) & (rg["level"] == 0.99)]
    regs = [x["name"] for x in cfg["backtest"]["regimes"]]
    first = _rec(rr.groupby("regime")[["expected", "n"]].first())
    lines += [
        "## Stress regimes (99% VaR exceptions; expected count in the header)",
        "",
        "| Model | "
        + " | ".join(f"{g} ({first[g]['n']} d, exp. {first[g]['expected']:.1f})" for g in regs)
        + " |",
        "|---|" + "---|" * len(regs),
    ]
    reg_rec = _rec(rr.set_index(["model", "regime"]))
    for m in models:
        cells = [
            f"{int(reg_rec[(m, g)]['exceptions'])}{' *' if reg_rec[(m, g)]['p_cc'] < alpha else ''}"
            for g in regs
        ]
        lines.append(f"| {LABEL[m]} | " + " | ".join(cells) + " |")
    lines += [
        "",
        f"\\* conditional-coverage test rejects at {alpha}. The portfolio is long CHF, so the January 2015 SNB "
        "floor removal (CHF +15% in a day) was a gain, not a loss: no model has an exception there.",
        "",
        "## Window sensitivity (main portfolio, 99% VaR)",
        "",
        "| Model | "
        + " | ".join(f"{x}d: rate / years passed" for x in cfg["backtest"]["windows_sensitivity"])
        + " |",
        "|---|" + "---|" * len(cfg["backtest"]["windows_sensitivity"]),
    ]
    sm = _rec(s[(s["portfolio"] == "main") & (s["level"] == 0.99)].set_index(["model", "window"]))
    ptabs = {x: passed_years(py, x, alpha) for x in cfg["backtest"]["windows_sensitivity"]}
    for m in models:
        cells = [
            f"{sm[(m, x)]['rate']:.2%} / {ptabs[x][m]['passed']}"
            for x in cfg["backtest"]["windows_sensitivity"]
        ]
        lines.append(f"| {LABEL[m]} | " + " | ".join(cells) + " |")

    lines += [
        "",
        f"## Model comparison ({w}-day window)",
        "",
        f"Diebold–Mariano tests against {LABEL[REF]} (Newey–West variance; negative statistic = lower loss than the "
        "reference). Model Confidence Set: 90% level, block bootstrap (block 20, 2000 reps).",
        "",
        "| Model | Pinball 99%: DM stat (p) | Pinball 97.5%: DM stat (p) | FZ0 97.5%: DM stat (p) |",
        "|---|---|---|---|",
    ]
    for m in models:
        if m == REF:
            continue
        cells = []
        for k in ("dm_pinball_0.99", "dm_pinball_0.975", "dm_fz0_0.975"):
            x = comp[k].get(m)
            cells.append("n/a" if x is None else f"{x['stat']:+.2f} ({_p(x['p_two_sided'])})")
        lines.append(f"| {LABEL[m]} | " + " | ".join(cells) + " |")
    for k, title in (("mcs_pinball_0.99", "pinball 99%"), ("mcs_fz0_0.975", "FZ0 97.5%")):
        inc = ", ".join(LABEL[x] for x in comp[k]["included"])
        lines.append(f"\n**MCS ({title}):** {inc}.")

    eq = _rec(s[(s["portfolio"] == "equal") & (s["level"] == 0.99)].set_index("model"))
    lines += [
        "",
        "## Robustness: equal-weight portfolio (99% VaR, same protocol)",
        "",
        "| Model | Exceptions | Rate | Kupiec p | Cond. coverage p |",
        "|---|---|---|---|---|",
    ]
    for m in models:
        r = eq[m]
        lines.append(
            f"| {LABEL[m]} | {int(r['exceptions'])} | {r['rate']:.2%} | {_p(r['p_uc'])} | {_p(r['p_cc'])} |"
        )

    sl = meta["shuffled_label_real"]
    lines += [
        "",
        "## Leakage checks",
        "",
        "- Unit tests (`tests/test_market.py`, marker `leakage`): forecasts for day t do not change when every return "
        "from t on is replaced; the ML features pass the causality check; on simulated GARCH data the LightGBM model "
        "beats historical simulation and loses that edge when trained on permuted targets.",
        f"- Same check on the real series (99%): pinball loss LightGBM {sl['lgbm_real']['pinball']:.5f}, with permuted "
        f"targets {sl['lgbm_shuffled']['pinball']:.5f}, historical simulation {sl['historical']['pinball']:.5f}.",
        "",
        "## Findings",
        "",
    ]
    lines += findings(main, py_tab, rg, comp, w, alpha)
    lines += [
        "",
        "## Limitations",
        "",
        "- One stylised FX/rates portfolio, no equities or credit spreads. Carry on FX cash and bond roll-down are "
        "ignored; the bond is a constant-maturity zero on the AAA curve (no basis or spread risk).",
        "- Backtests have low power: 2.5 expected exceptions per year at 99%. Per-year passes are an indication, the "
        "full-sample tests carry more weight.",
        "- Z2 zones are the indicative thresholds suggested by Acerbi & Szekely (see `docs/versions.md`), not "
        "simulated per model.",
        "- The ML models produce VaR only (direct quantile) or use in-sample residuals (volatility + FHS); both are "
        "simple, defensible baselines, not an exhaustive ML search.",
        "- GARCH fits occasionally report optimizer warnings; non-finite fits are refitted from default start values.",
        "",
    ]
    return "\n".join(lines)


def findings(  # noqa: PLR0917
    main: Rec, py_tab: Rec, rg: pd.DataFrame, comp: dict[str, Any], w: int, alpha: float
) -> list[str]:
    out = []
    ref_pass = int(py_tab[REF]["passed"])
    weak = {m: int(py_tab[m]["passed"]) for m in ("historical", "normal")}
    out.append(
        f"- **H2:** {LABEL[REF]} passes {ref_pass} of {int(py_tab[REF]['years'])} years, historical simulation "
        f"{weak['historical']}, normal {weak['normal']}."
    )
    gfc = _rec(rg[(rg["window"] == w) & (rg["level"] == 0.99) & (rg["regime"] == "GFC")].set_index("model"))
    out.append(
        f"- **Normal VaR in stress:** {int(gfc['normal']['exceptions'])} exceptions in the GFC regime vs "
        f"{gfc['normal']['expected']:.1f} expected (historical simulation {int(gfc['historical']['exceptions'])}, "
        f"FHS {int(gfc[REF]['exceptions'])}). Unconditional models react to a volatility jump only as the window "
        "rolls; GARCH-type models react the next day."
    )
    best_ml = max(ML, key=lambda m: int(py_tab[m]["passed"]))
    worst_garch = min(GARCH, key=lambda m: int(py_tab[m]["passed"]))
    out.append(
        f"- **H3:** the better ML model ({LABEL[best_ml]}) passes {int(py_tab[best_ml]['passed'])} years and "
        f"has a full-sample 99% exception rate of {main[(best_ml, 0.99)]['rate']:.2%}; the weakest GARCH model "
        f"({LABEL[worst_garch]}) passes {int(py_tab[worst_garch]['passed'])}. "
        + (
            "At least one ML model is"
            if any(m in comp["mcs_pinball_0.99"]["included"] for m in ML)
            else "No ML model is"
        )
        + " in the 90% MCS for 99% pinball loss."
    )
    gt = main[("garch_t", 0.99)]
    out.append(
        f"- **Conservatism vs accuracy:** plain GARCH-t has fewer exceptions than expected at 99% "
        f"({gt['rate']:.2%}); FHS and conditional EVT, which use the empirical residual tail, are closer to 1% "
        f"({main[(REF, 0.99)]['rate']:.2%} and {main[('evt_garch_t', 0.99)]['rate']:.2%})."
    )
    ind_fail = [LABEL[m] for m in (REF, "evt_garch_t") if main[(m, 0.975)]["p_ind"] < alpha]
    if ind_fail:
        out.append(
            f"- **Open issue:** at 97.5% the exceptions of {', '.join(ind_fail)} cluster (independence test rejects at "
            f"{alpha}), so even the best models miss some volatility regime changes."
        )
    return out
