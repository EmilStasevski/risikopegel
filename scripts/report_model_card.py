"""Model card for the Home Credit PD champion, generated from results/ only (PLAN §0 rule 1, §7)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

RESULTS = Path("results")


def _f(x: float, nd: int = 4) -> str:
    return f"{x:.{nd}f}"


def model_card() -> str | None:
    rp, ep = RESULTS / "credit/hc_challengers/results.json", RESULTS / "credit/hc_explain/explain.json"
    if not (rp.exists() and ep.exists()):
        return None
    r: dict[str, Any] = json.loads(rp.read_text())
    e: dict[str, Any] = json.loads(ep.read_text())
    c = r["champion"]["name"]
    m, s = r["models"][c], r["models"]["scorecard"]
    d = r["data"]
    ex, rc = e["models"][c], e["reason_codes"]
    cut = m["at_cutoff"]
    g = cut["groups"]
    sg = s["at_cutoff"]["groups"]
    top = list(ex["top10_terms"].items())
    rank_corr = e["importance_rank_corr_vs_champion"]
    L = [
        f"# Model card: Home Credit PD model (champion: `{c}`)",
        "",
        "_Generated by `scripts/report.py` from `results/credit/hc_challengers/results.json` "
        f"(run {r['run']['utc']}) and `results/credit/hc_explain/explain.json` (run {e['run']['utc']}). "
        "Portfolio project, not a production model; no regulatory compliance is claimed._",
        "",
        "## 1. Purpose and scope",
        "",
        "- **Purpose:** estimate the probability of default (PD) of a consumer-credit applicant at "
        "application time, for ranking (approve/decline at a cutoff) and as a PD input to ECL (Module A).",
        "- **Target:** Home Credit `TARGET` (payment difficulties on the loan, as defined by the data "
        "provider). Not a Basel default definition.",
        "- **Out of scope:** pricing, limit setting, behavioural scoring, corporate borrowers, any real "
        "lending decision.",
        "- **Regulatory context (supports, does not comply):** credit scoring of natural persons is listed "
        "as high-risk in EU AI Act Annex III 5(b); GDPR Art. 22 restricts solely automated decisions. The "
        "pipeline supports documentation, explainability (reason codes), group monitoring and drift "
        "monitoring; it does not implement human oversight, data governance or conformity assessment.",
        "",
        "## 2. Data",
        "",
        f"- {d['dataset']}; split: {d['split']}.",
        f"- train {d['train']:,} / valid {d['valid']:,} / test {d['test']:,}; test default rate "
        f"{_f(d['test_default_rate'])}; {d['n_features']} features ({len(d['categorical'])} categorical).",
        f"- Excluded from features: {', '.join(d['excluded_from_features'])}.",
        "- History features use only records dated before the application (dbt data tests).",
        "- **Known data issue:** monthly bureau history covers far fewer train than Kaggle-test applicants "
        "(see `reports/credit_hc_time_proxy.md`). Modelled explicitly: `bureau_history_status` "
        "(no bureau / bureau without history / with history) and `bureau_history_coverage`.",
        "- Population: Home Credit customers (largely un-/underbanked consumers); not a German population.",
        "",
        "## 3. Model",
        "",
        f"- Champion: **{c}**, chosen by the pre-set rule *{r['champion']['rule']}* (never on test). "
        f"Selected params `{json.dumps(m['selected_params'])}`, iterations {m['best_iteration']}, "
        f"fit {_f(m['fit_seconds'], 1)} s.",
        "- Benchmark: WoE/logistic scorecard (optbinning, monotonic bins, PDO 20 / 600 points at 50:1).",
        "",
        "## 4. Performance on test (scored once)",
        "",
        "| Metric | Champion | Scorecard |",
        "|---|---|---|",
        *[
            f"| {lab} | {_f(m['test'][k])} | {_f(s['test'][k])} |"
            for lab, k in (
                ("AUC", "auc"),
                ("Gini", "gini"),
                ("KS", "ks"),
                ("PR-AUC", "pr_auc"),
                ("Brier", "brier"),
                ("Calibration slope", "calibration_slope"),
                ("Calibration intercept", "calibration_intercept"),
                ("ECE", "ece"),
            )
        ],
        f"| ECE after Platt (fit on valid) | {_f(m['test_platt']['ece'])} | {_f(s['test_platt']['ece'])} |",
        f"| ECE after isotonic (fit on valid) | {_f(m['test_isotonic']['ece'])} | "
        f"{_f(s['test_isotonic']['ece'])} |",
        f"| Train AUC (overfit check) | {_f(m['train_auc'])} | {_f(s['train_auc'])} |",
        "",
        f"ΔAUC champion − scorecard: {m['vs_scorecard']['auc_diff']:+.4f} "
        f"(95% paired-bootstrap CI [{m['vs_scorecard']['ci95_low']:+.4f}, {m['vs_scorecard']['ci95_high']:+.4f}]).",
        "",
        "![Calibration](figures/hc_calibration.png)",
        "",
        f"## 5. Decision view (illustrative policy: approve {int(cut['approval_rate_target'] * 100)}%, "
        "cutoff fixed on valid)",
        "",
        "| Group | Approval rate | Default rate among approved | Defaulters declined | Non-defaulters declined |",
        "|---|---|---|---|---|",
        *[
            f"| {k} ({mod}) | {_f(gg[k]['approval_rate'], 3)} | {_f(gg[k]['default_rate_approved'], 4)} | "
            f"{_f(gg[k]['share_defaulters_rejected'], 3)} | {_f(gg[k]['share_goods_rejected'], 3)} |"
            for mod, gg in (("champion", g), ("scorecard", sg))
            for k in ("all", "F", "M")
        ],
        "",
        "Gender is not a model input; the table shows outcomes by group only. Differences can come from "
        "real risk differences (default rates differ by group) or from proxies; this check does not "
        "separate the two and is not a legal fairness assessment.",
        "",
        "## 6. Explainability",
        "",
        f"- Method: {ex['method']}; additivity check max |error| {ex['additivity_max_abs_error_logit']:.2e} "
        "logits (base + contributions = model log-odds).",
        "- Top global drivers (mean |contribution|, log-odds): "
        + ", ".join(f"{k} ({_f(v, 3)})" for k, v in top[:8])
        + ".",
        "- Rank agreement of global importance with other models (Spearman): "
        + ", ".join(f"{k} {_f(v, 2)}" for k, v in rank_corr.items())
        + ".",
        f"- Reason codes (top-3 risk-increasing terms) for the {rc['n_rejected_both']:,} test applicants "
        f"declined by both champion and scorecard: same top reason in {_f(rc['agreement']['top1_shared'], 3)} "
        f"of cases, mean Jaccard of top-3 {_f(rc['agreement']['mean_jaccard_top3'], 3)}. "
        f"Declined-set overlap (Jaccard) {_f(rc['rejection_overlap_jaccard'], 3)}.",
        "- Scorecard reason codes use points lost vs the best bin; champion codes use contributions vs "
        "the average applicant (SHAP convention). Both conventions are defensible; they are not identical.",
        "",
        "![Importance](figures/hc_importance.png)",
        "",
        "## 7. Stability and monitoring plan",
        "",
        f"- Score PSI train → Kaggle test (drift scenario): {_f(m['psi_train_to_kaggle'])}; "
        f"valid → test {_f(m['psi_valid_to_test'])}.",
        "- Monthly monitoring (proposed): score PSI and CSI of the top-10 drivers against the development "
        "sample; calibration by PD decile once outcomes mature (≥ 12 months); approval-rate and outcome "
        "metrics by group.",
        "- **Retraining / review rule (proposed):** score PSI > 0.10 → investigate; > 0.25 → re-validate "
        "and consider retraining. CSI > 0.25 on a top-10 driver → data-pipeline check first (the bureau "
        "coverage artefact shows that a large CSI can be a data change, not a population change). "
        "Observed/predicted default ratio outside [0.8, 1.25] for two consecutive quarters → recalibrate.",
        "",
        "![Score shift](figures/hc_score_shift.png)",
        "",
        "## 8. Limitations",
        "",
        "- No time dimension: evaluation is a stratified split; out-of-time performance is unknown.",
        "- The Kaggle test population is shifted and unlabelled; performance under that shift is unknown.",
        "- Target definition and population differ from a German retail portfolio; results do not transfer.",
        "- Small tuning grids; the gain over the scorecard may grow slightly with more tuning, which would "
        "not change the conclusions on calibration and stability.",
        "- Group check covers one attribute and does not test for proxy discrimination.",
        "",
    ]
    return "\n".join(L)
