"""Module E report: simplified Risikotragfähigkeit (reports/rtf.md), built from results/rtf/rtf.json only."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

SRC = Path("results/rtf/rtf.json")
RISK = {"credit": "Credit risk", "market": "Market risk", "irrbb": "Interest-rate risk (banking book)",
        "op": "Operational risk"}  # fmt: skip


def rtf_report() -> str | None:
    if not SRC.exists():
        return None
    r: dict[str, Any] = json.loads(SRC.read_text())
    cfg, cr, mk, ir, eco, nm, rev = (r[k] for k in ("config", "credit", "market", "irrbb", "economic", "normative",
                                                     "reverse_stress"))  # fmt: skip
    conf = cfg["economic"]["confidence"]
    lines = [
        "# Risikotragfähigkeit (ICAAP) of a stylised bank (Module E)",
        "",
        f"_Generated by `scripts/report.py` from `{SRC}` (run {r['run']['utc']}). **Every balance-sheet figure, LGD, "
        "correlation, limit and profit assumption is invented for illustration** (`config/rtf.toml`), not data about "
        "a real bank. The regulatory formulas are checked against the primary texts (`docs/module_e_rtf.md`). EUR "
        "millions. No claim of regulatory compliance._",
        "",
        "## The bank",
        "",
        f"- CET1 {cfg['bank']['cet1']:,.0f}. Retail credit book {cfg['credit_book']['ead_total']:,.0f} EAD: "
        f"{cr['n_loans']:,} loans with the Module A champion's PDs (EAD-weighted PD {cr['ead_weighted_pd']:.2%}, "
        f"PD floor {cfg['credit_book']['pd_floor']:.2%}) and LGD {cfg['credit_book']['lgd']:.0%}.",
        f"- Fixed-rate banking-book assets {cfg['other_assets']['fixed_rate_assets']:,.0f}; trading book "
        f"{cfg['other_assets']['trading_book']:,.0f} (the Module B FX/rates portfolio); deposits "
        f"{cfg['irrbb']['deposits']:,.0f}; wholesale funding {cfg['irrbb']['wholesale']:,.0f}.",
        "",
        f"## Economic perspective (1 year, {conf:.1%})",
        "",
        "| Risk type | Method | Economic capital | Limit | Limit use |",
        "|---|---|---|---|---|",
    ]
    method = {
        "credit": f"One-factor Gaussian copula MC ({cfg['economic']['n_sims']:,} scenarios), CRR retail correlation; UL = VaR − EL",
        "market": f"Module B FHS GARCH-t 99% 1-day VaR ({mk['var99_1d_pct']:.3f}% on {mk['var_date']}), √{cfg['economic']['market_holding_days']} days, scaled to {conf:.1%}",
        "irrbb": f"Historical simulation: {ir['hist_n_windows']} one-year ECB AAA curve changes since {ir['hist_first_window']}, ΔEVE quantile",
        "op": "CRR Art. 313 BIC = 0.12 × business indicator (proxy)",
    }
    for k, label in RISK.items():
        lim = eco["limits"][k]
        lines.append(
            f"| {label} | {method[k]} | {eco['ec'][k]:,.1f} | {lim['limit']:,.1f} | {lim['use']:.0%} ({lim['light']}) |"
        )
    lines += [
        f"| **Total, simple sum** | | **{eco['total_simple_sum']:,.1f}** | risk cover {eco['risk_cover']:,.0f} | "
        f"**{eco['utilisation_sum']:.0%} ({eco['traffic_light_total']})** |",
        f"| Total, variance–covariance | assumed correlations | {eco['total_var_covar']:,.1f} | | "
        f"{eco['utilisation_var_covar']:.0%} (diversification {eco['diversification_pct']:.0f}%) |",
        "",
        "Traffic light (internal convention, an assumption): green below 80% use, amber 80–100%, red above 100%.",
        "",
        "### Credit risk detail",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Expected loss (MC) | {cr['mc']['el']:,.1f} |",
        f"| VaR {conf:.1%} (MC) | {cr['mc']['var']:,.1f} |",
        f"| ES {conf:.1%} (MC) | {cr['mc']['es']:,.1f} |",
        f"| Unexpected loss (MC) | {cr['mc']['ul']:,.1f} |",
        f"| IRB capital requirement K (CRR Art. 154, closed form) | {cr['irb_k']:,.1f} |",
        f"| IRB expected loss | {cr['irb_el']:,.1f} |",
        f"| IRB RWA | {cr['irb_rwa']:,.0f} |",
        f"| EAD-weighted asset correlation | {cr['mean_correlation']:.3f} |",
        "",
        "Sensitivity of the MC unexpected loss:",
        "",
        "| Variant | UL | ES |",
        "|---|---|---|",
    ]
    for k, s in cr["mc_sensitivity"].items():
        lines.append(
            f"| {k.replace('_x', ' × ').replace('lgd_', 'LGD ')} | {s['ul']:,.1f} | {s['es']:,.1f} |"
        )
    lines += [
        "",
        "### Interest-rate risk in the banking book",
        "",
        f"ECB AAA spot curve of {ir['curve_date']}; EVE (assets − deposits − wholesale) {ir['eve_base']:,.1f}. "
        "EU supervisory shocks (Reg. (EU) 2024/856: EUR parallel 200, short 250, long 100 bp; post-shock floor):",
        "",
        "| Scenario | ΔEVE |",
        "|---|---|",
    ]
    for k, v in ir["delta_eve_supervisory"].items():
        lines.append(f"| {k} | {v:+,.1f} |")
    lines += [
        "",
        f"- Supervisory outlier test (EVE): worst ΔEVE {ir['worst_delta_eve']:+,.1f} ({ir['worst_scenario']}) = "
        f"{ir['sot_eve_ratio_tier1']:.1%} of Tier 1 against the 15% threshold → "
        f"{'**outlier**' if ir['sot_eve_outlier'] else 'not an outlier'}.",
        f"- NII test: ΔNII parallel up {ir['delta_nii_parallel']['parallel_up']:+,.1f}, down "
        f"{ir['delta_nii_parallel']['parallel_down']:+,.1f}; worst = {ir['sot_nii_ratio_tier1']:.1%} of Tier 1 against "
        f"5% → {'**outlier**' if ir['sot_nii_outlier'] else 'not an outlier'}.",
        f"- Historical simulation: {conf:.1%} loss quantile {ir['hist_loss_quantile']:,.1f}, worst window "
        f"{ir['hist_worst_loss']:,.1f}. Windows overlap, so the extreme quantile rests on few independent episodes.",
        "",
        f"Market risk with a 60-day holding period instead: {mk['ec_60d']:,.1f}.",
        "",
        "## Normative perspective (3 years, CET1 ratio)",
        "",
        f"Requirement {nm['requirement']:.2%} (Pillar 1 4.5% + assumed P2R share + 2.5% capital conservation buffer); "
        f"internal target {nm['target']:.2%}. PD paths from the R4 macro scenarios (`reports/credit_ecl.md`); "
        f"the adverse path also takes the worst historical 1-year loss of the trading portfolio "
        f"({mk['worst_1y_return_pct']:.1f}%) in year 1. Credit book replenished at constant size. Profit before "
        f"credit losses {nm['pre_provision_profit']:,.1f} per year: the consumer book is priced at its expected-loss "
        f"rate at today's PDs plus {cfg['normative']['credit_book_spread_over_el']:.0%}, other assets earn "
        f"{cfg['normative']['other_assets_net_margin']:.1%}; payout {cfg['normative']['payout_ratio']:.0%}. "
        "(The first run used a flat 0.8% return on assets, which ignored risk-based pricing and made the ~8% PD "
        "book loss-making every year by construction; corrected before any result was reported.)",
        "",
        "| Scenario | Year 0 | Year 1 | Year 2 | Year 3 | Minimum vs requirement |",
        "|---|---|---|---|---|---|",
    ]
    for s, p in nm["paths"].items():
        mn = min(x["ratio"] for x in p)
        state = (
            "below requirement"
            if mn < nm["requirement"]
            else ("below target" if mn < nm["target"] else "above target")
        )
        lines.append(f"| {s} | " + " | ".join(f"{x['ratio']:.2%}" for x in p) + f" | {mn:.2%} ({state}) |")
    lines += [
        "",
        "| Scenario | Year | Credit loss | Market loss | Net income | CET1 | RWA |",
        "|---|---|---|---|---|---|---|",
    ]
    for s, p in nm["paths"].items():
        for x in p[1:]:
            lines.append(f"| {s} | {x['year']} | {x['credit_loss']:,.1f} | {x['market_loss']:,.1f} | {x['net_income']:+,.1f} | "
                         f"{x['cet1']:,.1f} | {x['rwa']:,.0f} |")  # fmt: skip
    rp = rev["pd_multiplier_breaching_cet1_requirement"]
    rb = rev["parallel_up_bp_using_up_risk_cover"]
    lines += [
        "",
        "## Reverse stress tests",
        "",
        f"- **Normative:** a uniform PD multiplier of **{rp:.2f}** (on today's PDs, all 3 years) brings the minimum "
        "CET1 ratio down to the requirement.",
        "- **Economic:** "
        + (
            f"a parallel upward rate shock of **{rb:.0f} bp** (with the other risk types at their current economic "
            "capital) uses up the whole risk cover."
            if rb is not None
            else "no parallel shock up to 2,000 bp uses up the risk cover on its own."
        ),
        "",
        "## What this shows and what it does not",
        "",
        "- It links the modules: Module A PDs drive credit capital and the normative path, Module B's VaR drives "
        "market capital, Module C's forecasts drive the macro scenarios (through the R4 satellite model), and the "
        "ECB curve drives IRRBB. Change an upstream model and the RTF figures change with it.",
        "- It is not a bank's ICAAP. There is no liquidity, concentration, business or model risk; no "
        "behavioural deposit model beyond a fixed repricing profile; no tax; no management actions.",
        "- `GET /rtf` on the API recomputes the economic perspective for other assumptions (LGD, book size, "
        "correlation scaling, confidence level).",
        "",
    ]
    return "\n".join(lines)
