"""R5 reports for Module D: verified German explanations (reports/llm_explanations.md) and the ECB tone
signal test (reports/llm_text_signal.md), built from results/ only."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd

EXP = Path("results/llm/explanations")
SIG = Path("results/llm/text_signal/signal.json")
VARIANT = {
    "template": "Template only (deterministic)",
    "zero_shot": "LLM zero-shot",
    "few_shot": "LLM few-shot",
    "verified_retry": "LLM few-shot + verifier + up to 2 retries",
}


def _p(x: float) -> str:
    return "<0.001" if x < 0.001 else f"{x:.3f}"


def llm_explanations() -> str | None:
    if not (EXP / "summary.json").exists():
        return None
    s: dict[str, Any] = json.loads((EXP / "summary.json").read_text())
    v, mc, run = s["variants"], s["mutation_check"], s["run"]
    texts = pd.read_csv(EXP / "texts.csv")
    lines = [
        "# Verified German credit explanations (Module D, part 1)",
        "",
        f"_Generated by `scripts/report.py` from `{EXP}/` (run {run['utc']}). Model `{run['model']}` via local Ollama "
        f"(digest `{run['model_digest'][:12]}`), thinking off, temperature {run['temperature']}. No applicant data "
        "leaves the machine._",
        "",
        "## Set-up",
        "",
        f"- {s['sample']['n']} Home Credit test applicants, 20 per PD decile of the champion "
        f"({s['sample']['champion']}). Facts per applicant: the {run['top_k_facts']} features with the largest "
        "|TreeSHAP| contribution and their direction, plus the PD rounded to a whole percent.",
        f"- Protected-like attributes (age, birth date, family status, children, household size) are never handed "
        f"to the text generator. In {s['sample']['raw_top4_with_sensitive']} of {s['sample']['n']} applicants one of "
        "them was among the raw top 4; the next feature was used instead. The model still uses them; that is a "
        "finding for the model card, not hidden here.",
        "- The **verifier** (`src/risikopegel/llm/verifier.py`) is deterministic. A text passes only if every named "
        "feature is in the facts, every sentence with a feature states the right direction, no number other than "
        "the PD appears, no forbidden wording (decisions, guarantees, legal claims, protected attributes) is used "
        "and at least 2 facts are named.",
        "",
        "## Verifier check (deliberately broken template texts)",
        "",
        f"The plain template passes the verifier in {mc['template_pass_rate']:.0%} of cases.",
        "",
        "| Mutation | Texts | Caught |",
        "|---|---|---|",
    ]
    for k, m in mc.items():
        if isinstance(m, dict):
            lines.append(f"| {k} | {m['n']} | {m['caught']} |")
    lines += [
        "",
        "## Results",
        "",
        "| Variant | Pass (faithful) | Hallucination (unseen feature or number) | Wrong direction | No direction | "
        "Forbidden wording | Protected attribute | Shipped faithful | Template fallback | Mean attempts |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for k, label in VARIANT.items():
        r = v[k]
        lines.append(
            f"| {label} | {r['pass_rate']:.1%} | {r['hallucination_rate']:.1%} | {r['wrong_direction_rate']:.1%} | "
            f"{r['no_direction_rate']:.1%} | {r['forbidden_rate']:.1%} | {r['sensitive_rate']:.1%} | "
            f"{r['shipped_faithful_rate']:.1%} | {r['fallback_rate']:.1%} | {r['mean_attempts']:.2f} |"
        )
    lines += [
        "",
        "For the retry variant, *pass* is the rate of LLM texts that pass within 3 attempts. *Shipped faithful* "
        "also counts the template fallback.",
        "",
        "| Variant | Readability (Amstad, higher = easier) | Words | Output tokens | Input tokens | Seconds | GPU J per explanation |",
        "|---|---|---|---|---|---|---|",
    ]
    for k, label in VARIANT.items():
        r = v[k]
        lines.append(
            f"| {label} | {r['amstad_mean']:.0f} | {r['words_mean']:.0f} | {r['tokens_out_mean']:.0f} | "
            f"{r['tokens_in_mean']:.0f} | {r['seconds_per_explanation']:.2f} | {r['gpu_joules_per_explanation']:.0f} |"
        )
    for var in ("zero_shot", "few_shot"):
        err = texts[(texts["variant"] == var) & (~texts["passed"])]["errors"].str.split(" \\| ").explode()
        top_err = err.str.split(":").str[0].value_counts().head(5)
        lines += ["", f"## Most common verifier errors ({VARIANT[var]})", ""]
        lines += [f"- {k}: {n}" for k, n in top_err.items()]
    lines += [
        "",
        "Most few-shot failures are garbled factor names: when a text names two external scores, the quantised "
        '4B model often corrupts the second one (for example "Auskunfte-Bei B", "Auskunfteigkeit C", or a '
        "Chinese character inside the word). The check for unrecognised factor wording was added to the verifier "
        "after a smoke test on 2026-11-21 and before the main run. Without it, these texts would have passed: "
        "a verifier is only as good as its list of failure modes.",
    ]
    ex = texts[(texts["variant"] == "verified_retry") & texts["passed"]].head(2)["text"].tolist()
    if ex:
        lines += ["", "## Example output (verified variant, passed)", ""] + [f"> {t}\n" for t in ex]
    z, r = v["zero_shot"], v["verified_retry"]
    lines += [
        "## Findings",
        "",
        f"- **H6:** without the verifier, {1 - z['pass_rate']:.1%} of zero-shot texts (few-shot "
        f"{1 - v['few_shot']['pass_rate']:.1%}) fail at least one check. With the verifier and up to 2 retries, "
        f"{r['pass_rate']:.1%} of LLM texts pass; {r['fallback_rate']:.1%} fall back to the template, so "
        f"{r['shipped_faithful_rate']:.1%} of shipped texts are verified.",
        f"- **Cost of the LLM:** {r['seconds_per_explanation']:.2f} s and {r['gpu_joules_per_explanation']:.0f} GPU J "
        "per verified explanation, against effectively zero for the template. The template is already faithful by "
        "construction. What the LLM adds is wording variety, at a measurable cost in risk and energy.",
        "",
        "## Limitations",
        "",
        "- The verifier checks consistency with the SHAP facts, not whether the SHAP attribution itself is a good "
        "explanation. It is strict by design: an ambiguous sentence counts as a failure.",
        "- Readability uses a German Flesch adaptation with a heuristic syllable count.",
        "- No human evaluation of tone or helpfulness. No claim of compliance with GDPR Art. 22 or the EU AI Act; "
        "the pipeline supports traceable, reproducible reason statements.",
        "",
    ]
    return "\n".join(lines)


def llm_text_signal() -> str | None:
    if not SIG.exists():
        return None
    s: dict[str, Any] = json.loads(SIG.read_text())
    c, run = s["corpus"], s["run"]
    lines = [
        "# ECB speech tone as a volatility signal (Module D, part 2)",
        "",
        f"_Generated by `scripts/report.py` from `{SIG}` (run {run['utc']}). Not investment advice._",
        "",
        "## Set-up",
        "",
        f"- Corpus: {c['n_speeches']} English ECB speeches, {c['first']} to {c['last']} (ECB speeches dataset, fetched "
        f"{c['dataset_fetched_utc']}). Texts stay local; only scores are stored (`results/llm/text_signal/tone_scores.csv`).",
        f"- Tone measures: an own short economic lexicon (positive minus negative stems); FinBERT (`{run['finbert']}`) "
        f"on 16 evenly spaced sentences (64 tokens each, a CPU budget); `{run['llm']}` zero-shot on the first 6,000 characters (integer −2..+2). The LLM "
        f"could not be parsed for {s['llm_scoring']['unparseable']} speeches. Cost: "
        f"{s['llm_scoring']['seconds_per_speech']:.2f} s and {s['llm_scoring']['gpu_joules_per_speech']:.0f} GPU J per speech.",
        f"- Weekly targets ({s['weeks']['first']} to {s['weeks']['last']}): (A) log realised volatility of the Module B "
        "portfolio, (B) log absolute weekly change of the 2-year AAA yield. HAR-type base model (lags 1, 4 and 13 "
        "weeks); the challenger adds tone (mean over the trailing 4 weeks). Out-of-sample from 2013 with an "
        "expanding window, refitted weekly.",
        "",
        "Spearman correlation between the tone measures:",
        "",
    ]
    corr = s["score_correlations"]
    names = list(corr)
    lines += ["| | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for a in names:
        lines.append(f"| {a} | " + " | ".join(f"{corr[a][b]:.2f}" for b in names) + " |")
    lines += [
        "",
        "## Results",
        "",
        "| Tone measure | Target | Std. tone coefficient [95% CI] (in-sample, HAC) | OOS MSE ratio (with tone / base) | DM stat (p) |",
        "|---|---|---|---|---|",
    ]
    tname = {"rv": "(A) log RV portfolio", "dy2": "(B) log |Δ 2y yield|"}
    for m, rr in s["results"].items():
        for t, r in rr.items():
            lines.append(f"| {m} | {tname[t]} | {r['tone_coef_std']:+.3f} [{r['tone_ci95'][0]:+.3f}, {r['tone_ci95'][1]:+.3f}] | "
                         f"{r['mse_ratio']:.3f} | {r['dm_stat']:+.2f} ({_p(r['dm_p'])}) |")  # fmt: skip
    best = min(
        ((m, t, r) for m, rr in s["results"].items() for t, r in rr.items()), key=lambda x: x[2]["mse_ratio"]
    )
    sig = [
        (m, t)
        for m, rr in s["results"].items()
        for t, r in rr.items()
        if r["dm_p"] < 0.05 and r["dm_stat"] < 0
    ]
    lines += [
        "",
        "## Findings",
        "",
        f"- **H5:** the largest out-of-sample gain is {100 * (1 - best[2]['mse_ratio']):.1f}% lower MSE ({best[0]}, "
        f"target {best[1]}). Significant out-of-sample improvements (DM, 5%): "
        + (", ".join(f"{m}/{t}" for m, t in sig) if sig else "none")
        + ".",
        "",
        "## Limitations",
        "",
        "- Weekly aggregation and a trailing 4-week window are fixed choices; no search over them, to avoid "
        "overfitting the test.",
        "- Speeches are not policy decisions; press conferences and monetary-policy statements are not in this corpus.",
        "- FinBERT was trained on financial news, not central-bank language.",
        "",
    ]
    return "\n".join(lines)
