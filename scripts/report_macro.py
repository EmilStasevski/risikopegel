"""R4 reports: macro forecasting benchmark (reports/macro_forecast.md) and scenario ECL (reports/credit_ecl.md),
built from results/ only."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, cast

import pandas as pd

SRC = Path("results/macro/forecast")
ECL = Path("results/credit/ecl/ecl.json")
LABEL = {
    "naive": "Naive (last value)",
    "seasonal_naive": "Seasonal naive",
    "ets": "ETS (AICc selection)",
    "arima": "ARIMA (AIC selection)",
    "lgbm_global": "LightGBM global (direct)",
    "chronos2": "Chronos-2 (zero-shot)",
    "chronos_bolt_small": "Chronos-Bolt small (zero-shot)",
    "timesfm25": "TimesFM 2.5 (zero-shot)",
}
CLASSICAL = ("seasonal_naive", "ets", "arima")
FM = ("chronos2", "chronos_bolt_small", "timesfm25")
SHORT = "bankrupt_de"


def _p(x: float) -> str:
    return "<0.001" if x < 0.001 else f"{x:.3f}"


def _rec(df: pd.DataFrame) -> dict[Any, dict[str, Any]]:
    return cast(dict[Any, dict[str, Any]], df.to_dict("index"))


def macro_forecast() -> str | None:
    if not (SRC / "forecast.json").exists():
        return None
    meta: dict[str, Any] = json.loads((SRC / "forecast.json").read_text())
    by_h = _rec(pd.read_csv(SRC / "by_h.csv").set_index(["model", "h"]))
    by_s = pd.read_csv(SRC / "by_series.csv")
    dm = _rec(pd.read_csv(SRC / "dm.csv").set_index(["reference", "model", "h"]))
    models = [m for m in LABEL if (m, 1) in by_h]
    hs = meta["protocol"]["horizons"]
    comp = meta["compute"]
    lines = [
        "# Macro forecasting benchmark (Module C)",
        "",
        f"_Generated by `scripts/report.py` from `{SRC}/` (run {meta['run']['utc']}). Not investment advice._",
        "",
        "## Set-up",
        "",
        f"- **Series:** {len(meta['series'])} monthly series from Eurostat (HICP, unemployment, industrial production, "
        "retail trade, bankruptcies), listed below. Values are the latest *revised* data, not real-time vintages, "
        "so all models share a mild look-ahead from revisions.",
        f"- **Protocol:** rolling origin, one forecast per month from {meta['protocol']['first_origin']} (at least "
        f"{meta['protocol']['min_train']} months of history), horizons {', '.join(map(str, hs))}. Each forecast sees "
        "only data up to its origin. Classical specifications are re-selected every January on data up to that "
        "origin and re-estimated at every origin. The foundation models run zero-shot (no fine-tuning) on CPU.",
        "- **Metrics:** MASE (scale: in-sample seasonal-naive MAE, m = 12, up to the origin), sMAPE, scaled pinball "
        "loss over the 10/50/90% quantiles (SPL, a CRPS approximation), 80% interval coverage. All models are scored "
        "on identical (series, origin, horizon) cells.",
        "- **DM test:** Diebold–Mariano against seasonal naive on scaled absolute errors, (a) pooled (mean over "
        "series per origin), (b) per series (count of series significantly better / worse at 5%).",
        "",
        "| Series | First | Last | Obs | Origins | NSA |",
        "|---|---|---|---|---|---|",
    ]
    for sid, s in meta["series"].items():
        lines.append(
            f"| {sid} | {s['first']} | {s['last']} | {s['n']} | {s['n_origins']} | {'yes' if s['seasonal_nsa'] else ''} |"
        )
    for metric, title, fmt in (("mase", "MASE (lower is better)", "{:.3f}"), ("spl", "Scaled pinball loss", "{:.3f}"),
                               ("smape", "sMAPE (%)", "{:.2f}"), ("coverage80", "80% interval coverage", "{:.0%}")):  # fmt: skip
        lines += [
            "",
            f"## {title}",
            "",
            "| Model | " + " | ".join(f"h={h}" for h in hs) + " |",
            "|---|" + "---|" * len(hs),
        ]
        for m in models:
            lines.append(f"| {LABEL[m]} | " + " | ".join(fmt.format(by_h[(m, h)][metric]) for h in hs) + " |")
    n_cells = by_h[(models[0], hs[0])]["n"]
    lines += [f"\nCells per horizon: {n_cells} (h=1)."]
    for ref in ("seasonal_naive", "ets"):
        lines += ["", f"## Diebold–Mariano vs {LABEL[ref]} (scaled absolute error)", "",
                  "| Model | " + " | ".join(f"h={h}: pooled stat (p); series better/worse" for h in hs) + " |",
                  "|---|" + "---|" * len(hs)]  # fmt: skip
        for m in models:
            if m == ref:
                continue
            cells = []
            for h in hs:
                r = dm[(ref, m, h)]
                if pd.isna(r["pooled_stat"]):
                    cells.append("identical forecasts")
                    continue
                cells.append(f"{r['pooled_stat']:+.2f} ({_p(r['pooled_p'])}); "
                             f"{r['series_better_sig']}/{r['series_worse_sig']} of {r['n_series']}")  # fmt: skip
            lines.append(f"| {LABEL[m]} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "Negative statistic = lower error than the reference. Seasonal naive is a weak reference here "
        "because most series are seasonally adjusted (it then acts as a 12-month random walk); at h = 12 naive "
        "and seasonal naive coincide. ETS is the reference that matters for H4.",
    ]

    # short vs long series (H4, second part)
    piv = by_s.pivot_table(index="model", columns="series", values="mase", aggfunc="mean")
    lines += ["", f"## Short series: {SHORT} vs the rest (MASE, mean over horizons)", "",
              f"`{SHORT}` starts in {meta['series'][SHORT]['first']} ({meta['series'][SHORT]['n']} observations), "
              "the other series have 25 years or more.", "",
              f"| Model | {SHORT} | Median of other series | Rank on {SHORT} |", "|---|---|---|---|"]  # fmt: skip
    rank = piv[SHORT].rank()
    others = piv.drop(columns=[SHORT]).median(axis=1)
    for m in models:
        v_short, v_other, v_rank = float(piv[SHORT][m]), float(others[m]), int(rank[m])
        lines.append(f"| {LABEL[m]} | {v_short:.3f} | {v_other:.3f} | {v_rank} |")

    lines += ["", "## Compute (CPU, wall time and CPU-package energy via RAPL)", "",
              f"Idle package power at the start: {meta['run']['idle_package_watts']:.1f} W; {meta['run']['cpu_count']} logical "
              "CPUs. Classical models run in parallel worker processes, the foundation models use torch threads. "
              "Energy is for the whole package, so it includes the idle share; the column above idle removes it.", "",
              "| Model | Forecasts | Wall s | ms per forecast | J per forecast | J above idle per forecast |",
              "|---|---|---|---|---|---|"]  # fmt: skip
    for m in models:
        c = comp[m]
        lines.append(f"| {LABEL[m]} | {c['n_forecasts']} | {c['seconds']:.1f} | {c['ms_per_forecast']:.1f} | "
                     f"{c['joules_per_forecast']:.2f} | {c['joules_above_idle_per_forecast']:.2f} |")  # fmt: skip
    lines += ["", "## Findings", ""]
    lines += findings(by_h, dm, comp, piv, hs)
    lines += [
        "",
        "## Limitations",
        "",
        "- Revised data, not real-time vintages; macro releases come with a lag the protocol ignores (the origin "
        "month's value is treated as known).",
        "- One run per model: foundation-model sampling noise is not averaged (Chronos and TimesFM quantile heads "
        "are deterministic given the context, so this matters little).",
        "- N-BEATS/NHITS were not run: `neuralforecast`/`darts` were not added, to keep the dependency set "
        "small. The global LightGBM is the trained-ML representative.",
        "- `statsforecast` could not be used (requires pandas < 3); statsmodels ETS/ARIMA with a small selection "
        "grid stand in for AutoETS/AutoARIMA.",
        "",
    ]
    return "\n".join(lines)


def findings(by_h: dict[Any, dict[str, Any]], dm: dict[Any, dict[str, Any]], comp: dict[str, Any],
             piv: pd.DataFrame, hs: list[int]) -> list[str]:  # fmt: skip
    out = []
    for h in hs:
        best_cl = min(CLASSICAL, key=lambda m: by_h[(m, h)]["mase"])
        best_fm = min(FM, key=lambda m: by_h[(m, h)]["mase"])
        best = min((m for (m, hh) in by_h if hh == h), key=lambda m: by_h[(m, h)]["mase"])
        out.append(
            f"- **h={h}:** best overall {LABEL[best]} (MASE {by_h[(best, h)]['mase']:.3f}); best classical "
            f"{LABEL[best_cl]} ({by_h[(best_cl, h)]['mase']:.3f}); best foundation model {LABEL[best_fm]} "
            f"({by_h[(best_fm, h)]['mase']:.3f})."
        )
    ets_j = comp["ets"]["joules_above_idle_per_forecast"]
    fm_j = {m: comp[m]["joules_above_idle_per_forecast"] for m in FM}
    out.append(
        "- **Compute:** energy above idle per forecast, ETS "
        f"{ets_j:.2f} J; " + ", ".join(f"{LABEL[m]} {v:.2f} J" for m, v in fm_j.items()) + "."
    )
    r = piv[SHORT].rank()
    out.append(
        f"- **Short series ({SHORT}):** ranks "
        + ", ".join(f"{LABEL[m]} {int(r[m])}" for m in (*FM, "ets", "arima"))
        + " (1 = lowest MASE)."
    )
    return out


def credit_ecl() -> str | None:
    if not ECL.exists():
        return None
    e: dict[str, Any] = json.loads(ECL.read_text())
    sat, sc, pf = e["satellite"], e["scenarios"]["drivers"], e["portfolio"]
    cfg = e["config"]
    u, ip = cfg["satellite"]["drivers"]
    lines = [
        "# Macro-conditional PD and scenario ECL (simplified IFRS 9 style)",
        "",
        f"_Generated by `scripts/report.py` from `{ECL}` (run {e['run']['utc']}). Simplified illustration: no claim "
        "of IFRS 9 compliance. Amounts in the dataset's currency units._",
        "",
        "## Satellite model",
        "",
        f"12-month log change of German business bankruptcies (`{cfg['satellite']['target']}`) regressed on the "
        f"12-month change of unemployment (`{u}`, pp) and of log industrial production (`{ip}`), with a dummy for "
        f"the COVInsAG suspension of the duty to file ({cfg['satellite']['covid_start']} to "
        f"{cfg['satellite']['covid_end']}). OLS, Newey–West SE ({cfg['satellite']['hac_lags']} lags), "
        f"{sat['n']} months ({sat['period']}), R² {sat['r2']:.2f}.",
        "",
        "| Term | Coefficient | HAC SE | 95% CI | p |",
        "|---|---|---|---|---|",
    ]
    for k in sat["coef"]:
        lines.append(f"| {k} | {sat['coef'][k]:+.3f} | {sat['se_hac'][k]:.3f} | [{sat['ci95'][k][0]:+.3f}, "
                     f"{sat['ci95'][k][1]:+.3f}] | {_p(sat['p'][k])} |")  # fmt: skip
    lines += [
        "",
        "## Macro scenarios (3 years)",
        "",
        "Baseline: ETS forecast from the last observation. Adverse: baseline plus the largest historical 12-month "
        "deterioration of each driver, reached in year 1 and kept.",
        "",
        "| Driver | Last | Baseline y1 / y2 / y3 | Adverse y1 / y2 / y3 | Largest 12m deterioration (month) |",
        "|---|---|---|---|---|",
    ]
    for k, d in sc.items():
        nd = 2 if k == u else 3

        def fmt(x: float, nd: int = nd) -> str:
            return f"{x:.{nd}f}"

        lines.append(f"| {k}{' (log)' if k == ip else ''} | {fmt(d['last'])} ({d['last_period']}) | "
                     f"{' / '.join(fmt(x) for x in d['baseline'])} | {' / '.join(fmt(x) for x in d['adverse'])} | "
                     f"{d['worst_12m_change']:+.3f} ({d['worst_12m_month']}) |")  # fmt: skip
    mult = e["pd_multiplier_by_year"]
    lines += ["", "PD multiplier exp(b·Δx) relative to today's macro state:", "",
              "| Scenario | Year 1 | Year 2 | Year 3 |", "|---|---|---|---|"]  # fmt: skip
    for s, v in mult.items():
        lines.append(f"| {s} | " + " | ".join(f"{x:.3f}" for x in v) + " |")
    lines += [
        "",
        "## ECL",
        "",
        f"Portfolio: {pf['n']:,} loans (Home Credit test split), EAD {pf['ead_total']:,.0f}, mean PD {pf['mean_pd']:.2%} "
        f"(observed default rate {pf['observed_default_rate']:.2%}), median term {pf['term_months_median']:.0f} months.",
        "",
        "| Scenario | Stage 1 loans | Stage 2 loans | ECL stage 1 | ECL stage 2 | ECL total | Coverage (ECL/EAD) |",
        "|---|---|---|---|---|---|---|",
    ]
    for s, t in e["ecl"].items():
        lines.append(f"| {s} | {t['stage1']['n']:,} | {t['stage2']['n']:,} | {t['stage1']['ecl']:,.0f} | "
                     f"{t['stage2']['ecl']:,.0f} | {t['ecl_total']:,.0f} | {t['coverage_pct']:.2f}% |")  # fmt: skip
    w = e["ecl_weighted"]
    lines += [
        "",
        f"**Probability-weighted ECL** (weights {', '.join(f'{k} {v:.0%}' for k, v in w['weights'].items())}): "
        f"{w['ecl_total']:,.0f}, coverage {w['coverage_pct']:.2f}%.",
        "",
        "## Assumptions (all from `config/ecl.toml`, none from data)",
        "",
        f"- LGD {cfg['portfolio']['lgd']:.0%} flat; EAD = credit amount, constant over the life; no discounting.",
        "- Remaining term = credit / monthly annuity (interest ignored), clipped to "
        f"{cfg['portfolio']['term_min_months']}–{cfg['portfolio']['term_max_months']} months.",
        f"- Stage 2 = 12-month PD ≥ {cfg['staging']['stage2_pd_threshold']:.0%} (no origination PD, so no relative "
        "SICR test); stage 3 empty.",
        "- The champion's PD is treated as a 12-month PD under today's macro conditions; Home Credit's target "
        "window is not documented as exactly 12 months.",
        "- Business bankruptcies stand in for retail default-rate dynamics; the elasticity is carried over 1:1.",
        "- Scenario weights are a judgement call.",
        "",
    ]
    return "\n".join(lines)
