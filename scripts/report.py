"""`task report`: rebuild every report in reports/ from results/ only (PLAN §0 rule 1)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd

RESULTS = Path("results")
REPORTS = Path("reports")


def _f(x: float, nd: int = 3) -> str:
    return f"{x:.{nd}f}"


def credit_gmsc_smoke() -> str | None:
    src = RESULTS / "credit/gmsc_smoke/metrics.json"
    if not src.exists():
        return None
    r: dict[str, Any] = json.loads(src.read_text())
    h, t, s = r["holdout"], r["train"], r["shuffled_label"]
    cv = pd.DataFrame(r["cv5_on_train"])
    coefs = pd.read_csv(RESULTS / "credit/gmsc_smoke/coefficients.csv")
    cal = pd.read_csv(RESULTS / "credit/gmsc_smoke/calibration_holdout.csv")
    ref = r["public_reference"]
    rows = [
        ("AUC", "auc"),
        ("Gini", "gini"),
        ("KS", "ks"),
        ("PR-AUC", "pr_auc"),
        ("Brier", "brier"),
        ("Calibration slope", "calibration_slope"),
        ("Calibration intercept", "calibration_intercept"),
        ("ECE (10 buckets)", "ece"),
        ("Default rate", "default_rate"),
        ("Mean PD", "mean_pd"),
    ]
    lines = [
        "# Smoke test: WoE scorecard on Give Me Some Credit",
        "",
        f"_Generated by `scripts/report.py` from `{src}` (run {r['run']['utc']}, seed {r['run']['seed']}, "
        f"optbinning {r['run']['optbinning']}, scikit-learn {r['run']['sklearn']})._",
        "",
        f"Data: {r['data']['dataset']}, {r['data']['rows']:,} rows; split: {r['data']['split']}. "
        "No time column, so no stability/drift claims are made from this run.",
        "",
        "| Metric | Train | Holdout | CV-5 on train (mean ± sd) |",
        "|---|---|---|---|",
    ]
    for label, k in rows:
        lines.append(
            f"| {label} | {_f(t[k], 4)} | {_f(h[k], 4)} | {_f(cv[k].mean(), 4)} ± {_f(cv[k].std(), 4)} |"
        )
    lines += [
        "",
        f"**Leakage guard (shuffled labels, {len(s['auc_scores'])} rounds):** mean AUC {_f(s['mean'])}, "
        f"SD {_f(s['sd'])}, SE {_f(s['se'])}; passed = {s['passed']} "
        f"(criterion |mean - 0.5| ≤ max({s['tolerance']}, {s['z']}·SE)). {s['note']}.",
        "",
        f"**Public reference:** top Kaggle leaderboard AUC {ref['top_leaderboard_auc']} ({ref['source']}). "
        f"Not directly comparable: {ref['note']}",
        "",
        "## Coefficients (on WoE)",
        "",
        "optbinning defines WoE = ln(share of non-defaults / share of defaults), so a higher WoE means lower "
        "risk and the coefficients are negative.",
        "",
        "| Variable | Coefficient |",
        "|---|---|",
        *[f"| {v} | {_f(c, 4)} |" for v, c in zip(coefs["variable"], coefs["coef"], strict=True)],
        "",
        "## Calibration on holdout (equal-frequency deciles)",
        "",
        "| Bucket | n | Mean PD | Observed default rate |",
        "|---|---|---|---|",
        *[
            f"| {int(b)} | {int(n)} | {_f(m, 4)} | {_f(d, 4)} |"
            for b, n, m, d in zip(cal["bucket"], cal["n"], cal["mean_pd"], cal["default_rate"], strict=True)
        ],
        "",
        "Bin tables, points per bin and binning summary: `results/credit/gmsc_smoke/*.csv`.",
        "",
    ]
    sub_path = RESULTS / "credit/gmsc_submission/manifest.json"
    if sub_path.exists():
        sub = json.loads(sub_path.read_text())
        ks, lb = sub.get("kaggle_score"), sub.get("leaderboard_reference")
        if ks:
            lines += [
                "## Kaggle late submission (official test set)",
                "",
                f"Model: {sub['model']}. Source: {ks['source']}.",
                "",
                "| | AUC |",
                "|---|---|",
                f"| Kaggle private | {ks['private_auc']} |",
                f"| Kaggle public | {ks['public_auc']} |",
                f"| Own holdout (smoke test) | {_f(h['auc'], 5)} |",
            ]
            if lb:
                lines += [
                    f"| Top of leaderboard | {lb['top_auc']} |",
                    "",
                    f"Gap to top: {_f(lb['top_auc'] - ks['private_auc'], 5)} AUC vs private score. "
                    f"Caveat: {lb['caveat']}.",
                ]
            lines.append("")
    return "\n".join(lines)


def credit_hc_time_proxy() -> str | None:
    src = RESULTS / "credit/hc_time_proxy.json"
    if not src.exists():
        return None
    r: dict[str, Any] = json.loads(src.read_text())
    iv, ai, at = r["id_vs_default"], r["adversarial_low_vs_high_id"], r["adversarial_train_vs_kaggle_test"]
    top = ", ".join(f"{k} ({v})" for k, v in at["top_univariate_abs_auc_minus_half"].items())
    abl2 = r["adversarial_train_vs_kaggle_test_without_bureau_balance_and_credit_annuity"]
    return "\n".join(
        [
            "# Home Credit: is there a time proxy?",
            "",
            f"_Generated by `scripts/report.py` from `{src}` (run {r['utc']}); "
            "script `scripts/hc_time_proxy.py`._",
            "",
            f"Train {r['rows_train']:,} rows, Kaggle test {r['rows_test']:,} rows, "
            f"{r['n_features']} mart features.",
            "",
            "| Check | Result |",
            "|---|---|",
            f"| Spearman SK_ID_CURR vs default | rho {_f(iv['spearman_rho'], 4)}, "
            f"p {_f(iv['spearman_p'], 3)} |",
            f"| Default rate by ID decile (chi-square) | p {_f(iv['chi2_p'], 3)}; "
            f"range {_f(min(iv['default_rate_by_id_decile']), 4)} to "
            f"{_f(max(iv['default_rate_by_id_decile']), 4)} |",
            f"| Adversarial AUC, low vs high ID (5-fold) | {_f(ai['cv5_auc'], 4)} |",
            f"| Adversarial AUC, train vs Kaggle test (5-fold) | {_f(at['cv5_auc'], 4)} |",
            f"| … without the 2 bureau_balance features | "
            f"{_f(r['adversarial_train_vs_kaggle_test_without_bureau_balance']['cv5_auc'], 4)} |",
            f"| … and without credit/annuity ratio | {_f(abl2['cv5_auc'], 4)} |",
            f"| bureau_balance coverage among applicants with bureau records | "
            f"train {_f(r['bureau_balance_coverage_given_bureau_record']['train'], 3)}, "
            f"Kaggle test {_f(r['bureau_balance_coverage_given_bureau_record']['kaggle_test'], 3)} |",
            "",
            f"Strongest single features separating train from test (|AUC - 0.5|): {top}.",
            "",
            "Reading: SK_ID_CURR carries no time or drift signal, so it can't be used for an "
            "out-of-time split. The Kaggle test set is a *shifted* population (product mix and "
            "loan terms). That is usable as a drift scenario for PSI/monitoring, but it has no labels. "
            "Part of the separability is a data-coverage artefact: monthly bureau_balance history exists "
            "for far fewer train applicants than test applicants. The shift stays large without those "
            "features.",
            "",
        ]
    )


def data_series() -> str | None:
    src = RESULTS / "data/series_manifest.json"
    if not src.exists():
        return None
    rows: list[dict[str, Any]] = json.loads(src.read_text())
    lines = [
        "# Statistical series (ECB, Bundesbank, Eurostat)",
        "",
        f"_Generated by `scripts/report.py` from `{src}`. Raw files are kept unmodified in "
        "`data/raw/<source>/`; catalog in `config/series.toml`._",
        "",
        "| id | source | flow / key | first | last | obs | missing | fetched (UTC) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['id']} | {r['source']} | `{r['flow']}/{r['key']}` | {r['first_period']} | "
            f"{r['last_period']} | {r['rows']} | {r['n_missing']} | {r['fetched_utc']} |"
        )
    cites = sorted({r["citation"] for r in rows})
    lines += ["", "Citations: " + "; ".join(cites) + ".", ""]
    return "\n".join(lines)


def credit_hc_challengers() -> str | None:
    src = RESULTS / "credit/hc_challengers/results.json"
    if not src.exists():
        return None
    r: dict[str, Any] = json.loads(src.read_text())
    m: dict[str, Any] = r["models"]
    d = r["data"]
    order = sorted(m, key=lambda k: -m[k]["test"]["auc"])
    lines = [
        "# Home Credit: WoE scorecard vs boosting challengers (R2, Q1/H1)",
        "",
        f"_Generated by `scripts/report.py` from `{src}` (run {r['run']['utc']}, seed {r['run']['seed']}). "
        + ", ".join(f"{k} {v}" for k, v in r["run"]["versions"].items())
        + "._",
        "",
        f"Data: {d['dataset']}. Split: {d['split']}: train {d['train']:,} / valid {d['valid']:,} / "
        f"test {d['test']:,}; {d['n_features']} features; "
        f"excluded: {', '.join(d['excluded_from_features'])}. "
        f"Test default rate {_f(d['test_default_rate'], 4)}.",
        "",
        "Each family: small fixed grid (`GRIDS` in the script), early stopping and selection on "
        "valid AUC only; test scored once.",
        "",
        "## Discrimination and calibration on test",
        "",
        "| Model | AUC | Gini | KS | PR-AUC | Brier | Cal. slope | Cal. intercept | ECE | "
        "ECE after Platt | Train AUC |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for k in order:
        t, tp = m[k]["test"], m[k]["test_platt"]
        lines.append(
            f"| {k} | {_f(t['auc'], 4)} | {_f(t['gini'], 4)} | {_f(t['ks'], 4)} | {_f(t['pr_auc'], 4)} | "
            f"{_f(t['brier'], 5)} | {_f(t['calibration_slope'], 3)} | {_f(t['calibration_intercept'], 3)} | "
            f"{_f(t['ece'], 4)} | {_f(tp['ece'], 4)} | {_f(m[k]['train_auc'], 4)} |"
        )
    lines += [
        "",
        f"## AUC difference vs scorecard (paired bootstrap, {r['run']['n_bootstrap']} resamples of test)",
        "",
        "| Model | ΔAUC | 95% CI | share of resamples with ΔAUC ≤ 0 |",
        "|---|---|---|---|",
    ]
    for k in order:
        if "vs_scorecard" in m[k]:
            b = m[k]["vs_scorecard"]
            lines.append(
                f"| {k} | {b['auc_diff']:+.4f} | [{b['ci95_low']:+.4f}, {b['ci95_high']:+.4f}] | "
                f"{_f(b['share_diff_le_0'], 3)} |"
            )
    lines += [
        "",
        "## Stability, cost and selected configuration",
        "",
        "PSI of the score distribution. Train → Kaggle test is the drift scenario (shifted population, "
        "see `credit_hc_time_proxy.md`); valid → test is a sanity check and should be ~0.",
        "",
        "| Model | PSI train→Kaggle | PSI valid→test | Fit s (selected) | Predict s (test) | Iterations | "
        "Selected params |",
        "|---|---|---|---|---|---|---|",
    ]
    for k in order:
        x = m[k]
        lines.append(
            f"| {k} | {_f(x['psi_train_to_kaggle'], 4)} | {_f(x['psi_valid_to_test'], 4)} | "
            f"{_f(x['fit_seconds'], 1)} | {_f(x['predict_seconds_test'], 2)} | {x['best_iteration']} | "
            f"`{json.dumps(x['selected_params'])}` |"
        )
    lines += [
        "",
        "## Group check: gender (not a model input)",
        "",
        "| Model | AUC F | AUC M | default rate F | mean PD F | default rate M | mean PD M |",
        "|---|---|---|---|---|---|---|",
    ]
    for k in order:
        g = m[k]["by_gender"]
        lines.append(
            f"| {k} | {_f(g['F']['auc'], 4)} | {_f(g['M']['auc'], 4)} | {_f(g['F']['default_rate'], 4)} | "
            f"{_f(g['F']['mean_pd'], 4)} | {_f(g['M']['default_rate'], 4)} | {_f(g['M']['mean_pd'], 4)} |"
        )
    csi = pd.read_csv(RESULTS / "credit/hc_challengers/csi_train_to_kaggle.csv").head(10)
    lines += [
        "",
        "## Largest feature shifts train → Kaggle test (CSI, top 10)",
        "",
        "| Feature | CSI |",
        "|---|---|",
        *[f"| {f} | {_f(v, 4)} |" for f, v in zip(csi["feature"], csi["csi"], strict=True)],
        "",
        "PSI/CSI reading (industry rule of thumb, not a regulation): < 0.1 stable, 0.1-0.25 watch, "
        "> 0.25 shift.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    REPORTS.mkdir(exist_ok=True)
    built = []
    for name, fn in {
        "credit_gmsc_smoke.md": credit_gmsc_smoke,
        "credit_hc_time_proxy.md": credit_hc_time_proxy,
        "data_series.md": data_series,
        "credit_hc_challengers.md": credit_hc_challengers,
    }.items():
        text = fn()
        if text is not None:
            (REPORTS / name).write_text(text)
            built.append(name)
    print("reports built:", ", ".join(built) or "none")


if __name__ == "__main__":
    main()
