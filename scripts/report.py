"""`task report`: rebuild every report in reports/ from results/ only (PLAN §0 rule 1)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd

RESULTS = Path("results")
REPORTS = Path("reports")


def _f(x: float, nd: int = 3) -> str:
    return f"{x:.{nd}f}"


def credit_gmsc_smoke() -> str | None:
    src = RESULTS / "credit/gmsc_smoke/metrics.json"
    if not src.exists():
        return None
    r: dict[str, Any] = json.loads(src.read_text())
    h, t, s = r["holdout"], r["train"], r["shuffled_label"]
    cv = pd.DataFrame(r["cv5_on_train"])
    coefs = pd.read_csv(RESULTS / "credit/gmsc_smoke/coefficients.csv")
    cal = pd.read_csv(RESULTS / "credit/gmsc_smoke/calibration_holdout.csv")
    ref = r["public_reference"]
    rows = [
        ("AUC", "auc"),
        ("Gini", "gini"),
        ("KS", "ks"),
        ("PR-AUC", "pr_auc"),
        ("Brier", "brier"),
        ("Calibration slope", "calibration_slope"),
        ("Calibration intercept", "calibration_intercept"),
        ("ECE (10 buckets)", "ece"),
        ("Default rate", "default_rate"),
        ("Mean PD", "mean_pd"),
    ]
    lines = [
        "# Smoke test: WoE scorecard on Give Me Some Credit",
        "",
        f"_Generated by `scripts/report.py` from `{src}` (run {r['run']['utc']}, seed {r['run']['seed']}, "
        f"optbinning {r['run']['optbinning']}, scikit-learn {r['run']['sklearn']})._",
        "",
        f"Data: {r['data']['dataset']}, {r['data']['rows']:,} rows; split: {r['data']['split']}. "
        "No time column, so no stability/drift claims are made from this run.",
        "",
        "| Metric | Train | Holdout | CV-5 on train (mean ± sd) |",
        "|---|---|---|---|",
    ]
    for label, k in rows:
        lines.append(
            f"| {label} | {_f(t[k], 4)} | {_f(h[k], 4)} | {_f(cv[k].mean(), 4)} ± {_f(cv[k].std(), 4)} |"
        )
    lines += [
        "",
        f"**Leakage guard (shuffled labels, {len(s['auc_scores'])} rounds):** mean AUC {_f(s['mean'])}, "
        f"SD {_f(s['sd'])}, SE {_f(s['se'])}; passed = {s['passed']} "
        f"(criterion |mean - 0.5| ≤ max({s['tolerance']}, {s['z']}·SE)). {s['note']}.",
        "",
        f"**Public reference:** top Kaggle leaderboard AUC {ref['top_leaderboard_auc']} ({ref['source']}). "
        f"Not directly comparable: {ref['note']}",
        "",
        "## Coefficients (on WoE)",
        "",
        "optbinning defines WoE = ln(share of non-defaults / share of defaults), so a higher WoE means lower "
        "risk and the coefficients are negative.",
        "",
        "| Variable | Coefficient |",
        "|---|---|",
        *[f"| {v} | {_f(c, 4)} |" for v, c in zip(coefs["variable"], coefs["coef"], strict=True)],
        "",
        "## Calibration on holdout (equal-frequency deciles)",
        "",
        "| Bucket | n | Mean PD | Observed default rate |",
        "|---|---|---|---|",
        *[
            f"| {int(b)} | {int(n)} | {_f(m, 4)} | {_f(d, 4)} |"
            for b, n, m, d in zip(cal["bucket"], cal["n"], cal["mean_pd"], cal["default_rate"], strict=True)
        ],
        "",
        "Bin tables, points per bin and binning summary: `results/credit/gmsc_smoke/*.csv`.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    REPORTS.mkdir(exist_ok=True)
    built = []
    for name, fn in {"credit_gmsc_smoke.md": credit_gmsc_smoke}.items():
        text = fn()
        if text is not None:
            (REPORTS / name).write_text(text)
            built.append(name)
    print("reports built:", ", ".join(built) or "none")


if __name__ == "__main__":
    main()
