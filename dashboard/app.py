"""Risikopegel dashboard (Streamlit): score distribution and PSI, VaR exceptions, macro forecasts, RTF.

Reads only results/ and the local forecast artifacts in data/processed/ (if present). Run:
    task dashboard        # = uv run --group dashboard streamlit run dashboard/app.py
Research project, not investment advice.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"


def load_json(rel: str) -> dict[str, Any] | None:
    p = RES / rel
    return json.loads(p.read_text()) if p.exists() else None


st.set_page_config(page_title="Risikopegel", layout="wide")
st.title("Risikopegel: model-risk dashboard")
st.caption("All figures come from results/ (generated by code). Research project, not investment advice.")
tab_credit, tab_market, tab_macro, tab_rtf = st.tabs(
    ["Credit (PD)", "Market (VaR)", "Macro forecasts", "RTF"]
)

with tab_credit:
    r = load_json("credit/hc_challengers/results.json")
    if r:
        champ = r["champion"]["name"]
        m = r["models"]
        rows = [
            {
                "model": k,
                "test AUC": v["test"]["auc"],
                "test ECE": v["test"]["ece"],
                "PSI train→Kaggle": v.get("psi_train_to_kaggle"),
            }
            for k, v in m.items()
        ]
        st.subheader(f"Model comparison (champion: {champ})")
        st.dataframe(pd.DataFrame(rows).set_index("model").style.format("{:.4f}"), width="stretch")
        csi = RES / "credit/hc_challengers/csi_train_to_kaggle.csv"
        if csi.exists():
            st.subheader("Feature stability (CSI, train → Kaggle test population)")
            c = pd.read_csv(csi).head(15).set_index("feature")
            st.bar_chart(c, horizontal=True)
            st.caption("Rule of thumb: < 0.1 stable, 0.1–0.25 watch, > 0.25 shift.")

with tab_market:
    s = RES / "market/backtest/summary.csv"
    if s.exists():
        df = pd.read_csv(s)
        level = st.radio("VaR level", [0.99, 0.975], horizontal=True)
        window = st.radio("Window (days)", sorted(df["window"].unique()), index=2, horizontal=True)
        t = df[(df["portfolio"] == "main") & (df["level"] == level) & (df["window"] == window)]
        st.dataframe(
            t[["model", "exceptions", "rate", "p_uc", "p_ind", "p_cc"]].set_index("model"), width="stretch"
        )
        fc = ROOT / "data/processed/market/forecasts.parquet"
        if fc.exists():
            f = pd.read_parquet(fc)
            models = st.multiselect(
                "Models", sorted(f["model"].unique()), default=["historical", "fhs_garch_t"]
            )
            g = f[
                (f["portfolio"] == "main")
                & (f["level"] == level)
                & (f["window"] == window)
                & f["model"].isin(models)
            ]
            wide = g.pivot(index="date", columns="model", values="var")
            wide["loss"] = g.drop_duplicates("date").set_index("date")["loss"].clip(lower=0)
            st.line_chart(wide)
    py = RES / "market/backtest/per_year.csv"
    if py.exists():
        st.subheader("Basel traffic light per calendar year (99%, 1000-day window)")
        p = pd.read_csv(py)
        p = p[(p["level"] == 0.99) & (p["window"] == 1000)].pivot(
            index="model", columns="year", values="zone"
        )
        st.dataframe(p, width="stretch")

with tab_macro:
    b = RES / "macro/forecast/by_h.csv"
    if b.exists():
        d = pd.read_csv(b)
        st.subheader("MASE by horizon (lower is better)")
        st.dataframe(
            d.pivot(index="model", columns="h", values="mase").style.format("{:.3f}"), width="stretch"
        )
        meta = load_json("macro/forecast/forecast.json")
        if meta:
            comp = pd.DataFrame(meta["compute"]).T[["ms_per_forecast", "joules_above_idle_per_forecast"]]
            st.subheader("Compute per forecast")
            st.dataframe(comp.style.format("{:.3f}"), width="stretch")
        fc = ROOT / "data/processed/macro/forecasts.parquet"
        if fc.exists():
            f = pd.read_parquet(fc)
            sid = st.selectbox("Series", sorted(f["series"].unique()))
            h = st.radio("Horizon", [1, 3, 12], horizontal=True)
            g = f[(f["series"] == sid) & (f["h"] == h)]
            g = g.assign(target=pd.PeriodIndex(g["origin"], freq="M") + h).assign(
                target=lambda x: x["target"].dt.to_timestamp()
            )
            wide = g.pivot(index="target", columns="model", values="q50")
            wide["actual"] = g.drop_duplicates("target").set_index("target")["actual"]
            st.line_chart(wide[["actual", *[c for c in ("seasonal_naive", "ets", "chronos2") if c in wide]]])

with tab_rtf:
    r = load_json("rtf/rtf.json")
    if r:
        eco = r["economic"]
        st.subheader("Economic perspective (stylised bank, all inputs are assumptions)")
        c1, c2, c3 = st.columns(3)
        c1.metric("Risk cover (EUR m)", f"{eco['risk_cover']:,.0f}")
        c2.metric("Economic capital, simple sum", f"{eco['total_simple_sum']:,.0f}")
        c3.metric(
            "Utilisation",
            f"{eco['utilisation_sum']:.0%}",
            help=f"traffic light: {eco['traffic_light_total']}",
        )
        lim = pd.DataFrame(eco["limits"]).T
        st.dataframe(lim, width="stretch")
        st.subheader("Normative perspective: CET1 ratio path")
        paths = {s: [x["ratio"] for x in p] for s, p in r["normative"]["paths"].items()}
        st.line_chart(pd.DataFrame(paths))
        st.caption(
            f"Requirement {r['normative']['requirement']:.2%}, internal target {r['normative']['target']:.2%}."
        )
